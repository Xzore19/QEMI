main_circ.u(pi/2,0.896000,param_4, qreg_0[0])
main_circ.u(param_4,-0.295000,0.145000, 1)
bindings = {param_0: -0.426000, param_1: 0.178000, param_2: -0.720000, param_3: 0.522000, param_4: 0.507000, }
