main_circ = QuantumCircuit(4)
# Adding qregs 
qreg_0 = QuantumRegister(1)
main_circ.add_register(qreg_0)
# Adding creg resources 
creg_0 = ClassicalRegister(1)
main_circ.add_register(creg_0)
creg_1 = ClassicalRegister(1)
main_circ.add_register(creg_1)
# Adding symbols 
param_0 = Parameter("param_0")
param_1 = Parameter("param_1")
param_2 = Parameter("param_2")
param_3 = Parameter("param_3")

main_circ.u(param_0,0.818000,0.452000, 2)
main_circ.ry(0.346000, 2)
main_circ.cx(qreg_0[0],1)
main_circ.ry(param_3, 2)
main_circ.cx(1,0)
main_circ.u(pi/2,0.053000,0.752000, 1)
main_circ.u(param_2,0,-0.409000, 1)
main_circ.cx(0,2)
main_circ.cx(qreg_0[0],3)
main_circ.ry(param_2, 2)
main_circ.u(0,param_1,-0.035000, 0)
main_circ.ry(-0.365000, 0)
main_circ.u(0,0,param_2, qreg_0[0])
main_circ.cx(3,2)
main_circ.u(pi/2,param_1,param_3, 3)
main_circ.cx(qreg_0[0],3)
main_circ.ry(param_1, 3)
main_circ.u(pi/2,0.806000,param_1, 3)
main_circ.ry(-0.974000, qreg_0[0])
main_circ.ry(param_2, 2)
main_circ.cx(qreg_0[0],2)
main_circ.u(0,param_1,param_2, 1)
main_circ.ry(param_3, 3)
main_circ.cx(qreg_0[0],2)
main_circ.u(param_0,param_1,param_0, 0)
main_circ.u(pi/2,-0.063000,param_0, 1)
main_circ.cx(2,1)
main_circ.ry(param_2, 3)
main_circ.u(pi/2,param_3,param_1, 1)
main_circ.ry(param_0, 3)
main_circ.u(pi/2,param_1,param_2, 2)
main_circ.u(param_0,param_1,0.777000, 1)
main_circ.u(param_3,param_2,0.177000, 1)
main_circ.cx(qreg_0[0],1)
main_circ.cx(0,qreg_0[0])
main_circ.cx(1,0)
main_circ.cx(qreg_0[0],3)
main_circ.cx(3,qreg_0[0])
main_circ.cx(3,0)
main_circ.u(0,param_0,0.434000, 0)
main_circ.cx(1,qreg_0[0])
main_circ.ry(param_0, 2)
main_circ.u(pi/2,param_0,-0.684000, 2)
main_circ.ry(param_0, 1)
main_circ.cx(2,1)
main_circ.ry(param_3, 0)
main_circ.u(param_0,0.353000,param_3, 0)
main_circ.cx(qreg_0[0],1)
main_circ.u(0,0,param_1, qreg_0[0])
main_circ.u(0,0,-0.307000, qreg_0[0])
bindings = {param_0: -0.907000, param_1: -0.017000, param_2: 0.484000, param_3: -0.270000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
compare_statevectors(main_circ, "CommutativeInverseCancellation")
