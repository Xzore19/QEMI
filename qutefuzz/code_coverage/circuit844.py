from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister
from qiskit.circuit import Parameter, ParameterVector
from helpers.qiskit_helpers import compare_statevectors, run_on_simulator, run_routing_simulation, run_pass_on_simulator
from pathlib import Path
from math import pi

main_circ = QuantumCircuit(2)
# Adding qregs 
qreg_0 = QuantumRegister(3)
main_circ.add_register(qreg_0)
qreg_3 = QuantumRegister(1)
main_circ.add_register(qreg_3)
# Adding creg resources 
creg_0 = ClassicalRegister(1)
main_circ.add_register(creg_0)
creg_1 = ClassicalRegister(1)
main_circ.add_register(creg_1)
# Adding symbols 
param_0 = Parameter("param_0")
param_1 = Parameter("param_1")

main_circ.u(param_1,0.711000,param_0, 0)
main_circ.u(pi/2,param_1,0.419000, 0)
main_circ.cy(1,qreg_0[0])
main_circ.rx(param_0, qreg_0[2])
main_circ.cy(qreg_0[2],0)
main_circ.x(qreg_0[2])
main_circ.x(qreg_0[0])
main_circ.rx(-0.820000, 1)
main_circ.cy(qreg_0[0],1)
main_circ.x(qreg_0[2])
main_circ.cy(1,0)
main_circ.cy(qreg_0[1],0)
main_circ.cy(qreg_0[0],qreg_3[0])
main_circ.rx(param_1, qreg_3[0])
main_circ.x(1)
main_circ.u(pi/2,0.480000,-0.929000, 1)
main_circ.rx(0.040000, 0)
main_circ.x(0)
main_circ.cy(0,qreg_0[2])
main_circ.cy(0,qreg_3[0])
main_circ.u(param_1,0.977000,0.790000, qreg_0[1])
main_circ.rx(0.515000, qreg_0[0])
main_circ.rx(-0.616000, 1)
main_circ.u(pi/2,param_1,param_0, 1)
main_circ.x(0)
main_circ.cy(qreg_0[2],qreg_0[0])
main_circ.u(pi/2,-0.731000,-0.407000, 0)
main_circ.x(qreg_0[2])
main_circ.cy(1,qreg_3[0])
main_circ.cy(qreg_0[2],0)
main_circ.cy(qreg_0[0],qreg_0[1])
main_circ.u(param_0,param_1,param_1, 1)
main_circ.rx(-0.468000, 1)
main_circ.x(qreg_0[1])
main_circ.u(param_0,-0.715000,param_1, qreg_3[0])
main_circ.cy(1,qreg_0[1])
main_circ.cy(qreg_3[0],0)
main_circ.x(qreg_0[0])
main_circ.cy(1,qreg_3[0])
main_circ.u(param_1,param_0,param_1, qreg_0[1])
bindings = {param_0: 0.011000, param_1: 0.470000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
main_circ.measure_active()
run_routing_simulation(main_circ, "844")
