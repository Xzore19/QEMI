main_circ.cx(1,qreg_0[0])
main_circ.cx(qreg_0[2],qreg_0[0])
main_circ.rz(-0.051000, 0)
main_circ.u(pi/2,0.467000,param_3, 1)
main_circ.u(param_2,param_1,-0.474000, qreg_0[0])
main_circ.u(param_3,0.903000,-0.346000, qreg_0[1])
main_circ.z(1)
main_circ.z(0)
main_circ.z(qreg_0[1])
main_circ.cx(0,qreg_0[2])
main_circ.z(1)
main_circ.z(1)
main_circ.cx(qreg_0[0],qreg_0[1])
main_circ.z(0)
main_circ.rz(param_2, qreg_0[3])
main_circ.cx(qreg_0[0],0)
main_circ.rz(0.205000, qreg_0[2])
main_circ.z(qreg_0[3])
main_circ.cx(qreg_0[1],qreg_0[3])
main_circ.z(qreg_0[3])
main_circ.z(qreg_0[2])
main_circ.rz(param_1, 0)
main_circ.z(qreg_0[3])
main_circ.rz(param_0, qreg_0[2])
main_circ.cx(0,qreg_0[3])
main_circ.cx(qreg_0[0],qreg_0[3])
main_circ.cx(0,qreg_0[0])
main_circ.cx(qreg_0[2],qreg_0[3])
main_circ.cx(qreg_0[0],qreg_0[2])
main_circ.cx(0,qreg_0[0])
main_circ.u(param_3,param_3,param_2, qreg_0[0])
main_circ.rz(param_4, 0)
main_circ.z(1)
main_circ.z(1)
main_circ.u(param_1,-0.623000,-0.539000, qreg_0[2])
main_circ.z(1)
main_circ.cx(qreg_0[3],1)
bindings = {param_0: -0.841000, param_1: 0.243000, param_2: 0.907000, param_3: -0.417000, param_4: -0.763000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
