main_circ.z(qreg_1[0])
main_circ.u(pi/2,param_1,0.540000, 3)
main_circ.rx(0.307000, 1)
main_circ.rx(0.382000, 1)
main_circ.u(param_1,-0.741000,-0.847000, 1)
main_circ.rx(param_0, 0)
main_circ.rx(param_0, qreg_1[0])
main_circ.z(1)
main_circ.rx(param_0, 0)
main_circ.rx(param_0, qreg_1[0])
main_circ.z(qreg_0[0])
main_circ.h(3)
main_circ.z(0)
main_circ.z(qreg_0[0])
main_circ.rx(-0.987000, qreg_1[0])
main_circ.rx(-0.414000, qreg_1[0])
main_circ.z(1)
main_circ.h(1)
main_circ.z(2)
main_circ.z(1)
main_circ.rx(-0.659000, 0)
main_circ.u(pi/2,param_2,param_0, 0)
