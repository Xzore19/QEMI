from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister
from qiskit.circuit import Parameter, ParameterVector
from helpers.qiskit_helpers import compare_statevectors, run_on_simulator, run_routing_simulation, run_pass_on_simulator
from pathlib import Path
from math import pi

main_circ = QuantumCircuit(1)
# Adding qregs 
qreg_0 = QuantumRegister(3)
main_circ.add_register(qreg_0)
qreg_3 = QuantumRegister(1)
main_circ.add_register(qreg_3)
# Adding creg resources 
creg_0 = ClassicalRegister(2)
main_circ.add_register(creg_0)
# Adding symbols 
param_0 = Parameter("param_0")
param_1 = Parameter("param_1")
param_2 = Parameter("param_2")
param_3 = Parameter("param_3")

main_circ.z(qreg_0[0])
main_circ.u(0,param_1,param_3, 0)
main_circ.z(qreg_0[0])
main_circ.cy(qreg_0[0],qreg_3[0])
main_circ.cy(0,qreg_3[0])
main_circ.y(qreg_0[1])
main_circ.z(qreg_0[0])
main_circ.z(qreg_3[0])
main_circ.u(0,param_3,param_2, qreg_0[2])
main_circ.u(param_1,0,param_2, qreg_0[0])
main_circ.y(0)
main_circ.cy(qreg_3[0],qreg_0[0])
main_circ.y(qreg_0[1])
main_circ.cy(qreg_0[1],qreg_3[0])
main_circ.u(0,0,param_1, 0)
main_circ.cy(qreg_0[0],qreg_0[1])
main_circ.z(qreg_0[1])
main_circ.y(qreg_0[0])
main_circ.y(qreg_3[0])
main_circ.z(0)
main_circ.y(qreg_0[0])
main_circ.cy(qreg_0[0],0)
main_circ.u(param_1,param_1,param_2, qreg_3[0])
main_circ.cy(qreg_0[1],0)
main_circ.cy(qreg_0[0],qreg_0[1])
main_circ.cy(qreg_3[0],qreg_0[0])
main_circ.u(0,param_1,param_0, qreg_0[1])
main_circ.u(0,0,-0.616000, qreg_0[1])
main_circ.u(param_1,param_1,0.381000, qreg_0[1])
main_circ.u(param_2,0,0.122000, 0)
main_circ.cy(qreg_0[0],qreg_0[1])
main_circ.cy(0,qreg_0[0])
main_circ.cy(qreg_0[1],qreg_0[0])
main_circ.cy(qreg_0[2],qreg_3[0])
main_circ.y(qreg_0[2])
main_circ.u(param_2,0,param_3, qreg_3[0])
main_circ.u(0,param_2,-0.089000, qreg_0[0])
main_circ.cy(qreg_3[0],qreg_0[1])
main_circ.cy(0,qreg_0[2])
main_circ.z(qreg_3[0])
main_circ.z(qreg_0[2])
main_circ.z(0)
main_circ.u(0,param_2,-0.596000, qreg_0[1])
bindings = {param_0: 0.202000, param_1: -0.677000, param_2: 0.655000, param_3: 0.819000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
compare_statevectors(main_circ, "OptimizeCliffords")
