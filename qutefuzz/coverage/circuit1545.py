from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister
from qiskit.circuit import Parameter, ParameterVector
from helpers.qiskit_helpers import compare_statevectors, run_on_simulator, run_routing_simulation, run_pass_on_simulator
from pathlib import Path
from math import pi

main_circ = QuantumCircuit(2)
# Adding qregs 
qreg_0 = QuantumRegister(2)
main_circ.add_register(qreg_0)
qreg_2 = QuantumRegister(1)
main_circ.add_register(qreg_2)
qreg_3 = QuantumRegister(1)
main_circ.add_register(qreg_3)
# Adding creg resources 
creg_0 = ClassicalRegister(2)
main_circ.add_register(creg_0)
# Adding symbols 
param_0 = Parameter("param_0")
param_1 = Parameter("param_1")
param_2 = Parameter("param_2")

main_circ.y(qreg_2[0])
main_circ.ry(param_0, qreg_2[0])
main_circ.y(qreg_2[0])
main_circ.ry(param_2, qreg_3[0])
main_circ.u(param_0,param_1,-0.612000, 0)
main_circ.ry(param_1, 1)
main_circ.u(pi/2,-0.702000,param_2, qreg_0[1])
main_circ.cx(qreg_3[0],0)
main_circ.cx(qreg_0[0],1)
main_circ.u(pi/2,-0.022000,-0.570000, qreg_0[1])
main_circ.y(qreg_2[0])
main_circ.cx(0,qreg_3[0])
main_circ.ry(0.619000, 1)
main_circ.cx(1,qreg_0[1])
main_circ.u(pi/2,param_0,param_1, 1)
main_circ.u(param_2,-0.884000,param_1, qreg_0[1])
main_circ.cx(qreg_0[0],1)
main_circ.ry(param_2, qreg_3[0])
main_circ.y(1)
main_circ.ry(param_1, 1)
main_circ.cx(qreg_2[0],qreg_0[1])
main_circ.ry(param_2, qreg_0[1])
main_circ.y(0)
main_circ.y(qreg_2[0])
main_circ.ry(-0.598000, qreg_3[0])
main_circ.u(pi/2,-0.031000,-0.626000, qreg_2[0])
main_circ.y(0)
main_circ.cx(qreg_0[0],qreg_0[1])
main_circ.u(param_2,-0.515000,param_0, 1)
main_circ.u(pi/2,param_0,-0.942000, qreg_0[0])
main_circ.y(1)
main_circ.cx(0,qreg_2[0])
main_circ.u(pi/2,0.156000,param_1, qreg_3[0])
main_circ.cx(qreg_2[0],1)
main_circ.cx(qreg_3[0],qreg_0[1])
main_circ.cx(qreg_2[0],qreg_3[0])
main_circ.ry(param_0, qreg_0[1])
main_circ.cx(qreg_0[1],qreg_3[0])
main_circ.cx(qreg_2[0],0)
main_circ.cx(1,qreg_2[0])
main_circ.cx(qreg_3[0],1)
main_circ.y(qreg_0[1])
main_circ.cx(1,qreg_0[1])
main_circ.ry(0.566000, qreg_3[0])
main_circ.ry(param_1, 0)
main_circ.ry(param_1, qreg_3[0])
main_circ.cx(qreg_3[0],qreg_2[0])
main_circ.ry(0.421000, qreg_3[0])
main_circ.y(qreg_0[0])
main_circ.cx(0,1)
main_circ.cx(qreg_2[0],1)
main_circ.cx(1,0)
bindings = {param_0: -0.361000, param_1: -0.443000, param_2: 0.560000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
main_circ.measure_active()
run_routing_simulation(main_circ, "1545")
