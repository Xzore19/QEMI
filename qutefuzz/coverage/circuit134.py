main_circ.z(1)
main_circ.u(param_5,param_3,0.135000, 2)
main_circ.rx(param_3, 2)
main_circ.u(param_4,0,param_2, 3)
main_circ.rx(-0.429000, qreg_0[0])
main_circ.u(param_3,param_1,param_5, 3)
bindings = {param_0: -0.678000, param_1: -0.392000, param_2: 0.071000, param_3: 0.566000, param_4: 0.811000, param_5: 0.552000, }
main_circ = main_circ.assign_parameters(bindings)

print(Path(__file__).name, " results:")
