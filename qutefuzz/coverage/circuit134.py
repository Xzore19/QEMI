main_circ.u(param_3,0,param_0, qreg_0[0])
main_circ.u(pi/2,param_0,param_0, 0)
main_circ.u(0,0,-0.303000, 0)
main_circ.z(3)
main_circ.u(pi/2,param_1,param_2, qreg_1[0])
main_circ.rx(param_3, 2)
main_circ.u(param_3,0,param_2, 3)
main_circ.u(param_5,param_0,param_5, 2)
main_circ.z(1)
main_circ.z(1)
main_circ.u(param_0,param_1,-0.100000, 1)
main_circ.z(3)
main_circ.u(param_2,param_2,0.523000, 1)
main_circ.u(0,0,param_1, 1)
main_circ.z(3)
main_circ.u(pi/2,0.012000,0.126000, 1)
main_circ.u(param_1,param_3,param_5, 3)
main_circ.z(qreg_0[0])
main_circ.rx(param_4, 2)
main_circ.u(pi/2,-0.531000,-0.756000, qreg_0[0])
