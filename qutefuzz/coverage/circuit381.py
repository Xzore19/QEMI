main_circ.ry(0.654000, 1)
main_circ.cy(2,0)
main_circ.cx(2,0)
main_circ.cy(qreg_0[0],1)
main_circ.cx(0,3)
main_circ.ry(param_1, 2)
main_circ.cx(0,qreg_0[0])
main_circ.ry(param_0, 3)
main_circ.cx(2,1)
main_circ.cx(0,2)
main_circ.ry(0.579000, 1)
main_circ.u(param_1,param_0,-0.729000, 1)
main_circ.u(pi/2,param_1,-0.093000, 1)
main_circ.cx(1,2)
main_circ.u(pi/2,0.295000,0.375000, 3)
main_circ.u(param_1,param_0,param_0, 3)
main_circ.cx(1,3)
main_circ.ry(param_0, qreg_0[0])
main_circ.cx(0,3)
main_circ.cy(0,qreg_0[0])
main_circ.cy(1,2)
main_circ.cy(3,1)
main_circ.ry(param_1, 3)
main_circ.ry(param_1, qreg_0[0])
main_circ.cy(2,0)
main_circ.cx(3,qreg_0[0])
main_circ.cx(1,3)
main_circ.cx(qreg_0[0],3)
main_circ.cx(0,3)
main_circ.cy(3,qreg_0[0])
main_circ.ry(param_0, 1)
main_circ.cx(qreg_0[0],1)
main_circ.cy(2,3)
main_circ.cx(0,1)
main_circ.ry(param_1, 3)
main_circ.ry(param_1, qreg_0[0])
main_circ.u(pi/2,param_1,param_0, 1)
main_circ.u(pi/2,0.342000,param_1, 2)
main_circ.u(pi/2,0.068000,-0.902000, 2)
main_circ.u(param_1,param_0,param_1, 1)
main_circ.cy(3,qreg_0[0])
main_circ.ry(-0.677000, 3)
bindings = {param_0: -0.285000, param_1: -0.147000, }
main_circ = main_circ.assign_parameters(bindings)

