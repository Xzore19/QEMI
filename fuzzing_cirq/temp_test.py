import cirq
from cirq.transformers import *

q = cirq.LineQubit.range(6) 
circuit = cirq.Circuit()


cirq.contrib.acquaintance.AcquaintanceOperation([q[0],q[4],q[3]], [0, 4, 3]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=5).on(q[1],q[4],q[2],q[0],q[3]) 
circuit.append(cirq.CSwapGate().on(q[4], q[2], q[0]))
circuit.append(cirq.rx(0.0030679615757712823).on(q[2]).controlled_by(q[1]))
circuit.append(cirq.H(q[1]))
circuit.append(cirq.QuantumFourierTransformGate(num_qubits=2).on(q[2],q[0]).controlled_by(q[1]))
circuit.append(cirq.ZZPowGate(exponent=0.19634954084936207).on(q[4], q[0]))
circuit.append(cirq.rx(0.006135923151542565).on(q[2]))
circuit.append(cirq.ZZPowGate(exponent=0.02454369260617026).on(q[0], q[2]))
circuit.append(cirq.XPowGate(exponent=0.01227184630308513).on(q[3]).controlled_by(q[1]))
circuit.append(cirq.X(q[2]).controlled_by(q[0]))
circuit.append(cirq.Z(q[3]))

cirq.contrib.acquaintance.AcquaintanceOperation([q[0],q[1],q[4],q[2],q[3]], [0, 1, 4, 2, 3]) 
cirq.contrib.acquaintance.AcquaintanceOpportunityGate(num_qubits=5).on(q[1],q[2],q[4],q[0],q[3]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=2).on(q[1],q[3]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=2, permutation={1: 1, 0: 0}).on(q[2],q[3]) 
sub_circuit = cirq.Circuit() 
sub_op = cirq.CircuitOperation(sub_circuit.freeze()) 
circuit.append(cirq.measure(q[5], key="c")) 
circuit.append(cirq.measure([q[0],q[2]], key="ca")) 
dc_cond = cirq.BitMaskKeyCondition.create_equal_mask('ca', bitmask=1)
circuit.append(sub_op.with_classical_controls("c", dc_cond)) 

cirq.contrib.acquaintance.AcquaintanceOperation([q[3],q[4]], [3, 4]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=2).on(q[3],q[2]) 
circuit.append(cirq.H(q[4]))
circuit.append(cirq.YPowGate(exponent=0.7853981633974483).on(q[4]))
circuit.append(cirq.X(q[1]))
circuit.append(cirq.PhasedISwapPowGate(phase_exponent=0.02454369260617026,exponent=0.19634954084936207).on(q[4], q[2]))
circuit.append(cirq.H(q[1]))
circuit.append(cirq.PhasedFSimGate(theta=1.5707963267948966, zeta=0.04908738521234052, chi=0.09817477042468103, gamma=0.01227184630308513, phi=0.04908738521234052).on(q[3], q[2]))
circuit.append(cirq.YPowGate(exponent=0.39269908169872414).on(q[0]).controlled_by(q[4]))
circuit.append(cirq.T(q[3]))
circuit.append(cirq.SQRT_ISWAP_INV(q[3], q[1]))
circuit.append(cirq.T(q[3]).controlled_by(q[2]))

cirq.contrib.acquaintance.AcquaintanceOpportunityGate(num_qubits=5).on(q[0],q[1],q[4],q[3],q[2]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=5).on(q[4],q[1],q[3],q[2],q[0]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=5, permutation={4: 4, 0: 2, 1: 0, 3: 3, 2: 1}).on(q[0],q[2],q[3],q[1],q[4]) 
circuit.append(cirq.measure(q, key="m")) 
circuit = merge_single_qubit_gates_to_phased_x_and_z(circuit)
circuit = defer_measurements(circuit)
circuit = merge_single_qubit_gates_to_phxz(circuit)
simulator = cirq.Simulator() 
result = simulator.run(circuit, repetitions=500) 
print(result.histogram(key='m'))