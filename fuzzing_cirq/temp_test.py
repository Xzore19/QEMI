import cirq
from cirq.transformers import *

q = cirq.LineQubit.range(6) 
circuit = cirq.Circuit()


cirq.contrib.acquaintance.AcquaintanceOperation([q[4],q[1],q[2]], [4, 1, 2]) 
cirq.contrib.acquaintance.AcquaintanceOpportunityGate(num_qubits=3).on(q[4],q[3],q[2]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=5).on(q[4],q[3],q[0],q[2],q[1]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=4, permutation={2: 2, 0: 3, 3: 0, 1: 1}).on(q[4],q[1],q[2],q[0]) 
circuit.append(cirq.MSGate(rads=0.19634954084936207).on(q[0], q[1]).controlled_by(q[4]))
circuit.append(cirq.SQRT_ISWAP_INV(q[0], q[2]).controlled_by(q[1]))
circuit.append(cirq.PhasedISwapPowGate(phase_exponent=0.09817477042468103,exponent=0.02454369260617026).on(q[1], q[3]).controlled_by(q[2]))
circuit.append(cirq.CCZ(q[3], q[1], q[0]))
circuit.append(cirq.SQRT_ISWAP_INV(q[2], q[1]).controlled_by(q[3]))
circuit.append(cirq.ry(0.006135923151542565).on(q[4]))
circuit.append(cirq.MSGate(rads=0.09817477042468103).on(q[4], q[2]).controlled_by(q[3]))
circuit.append(cirq.rx(0.006135923151542565).on(q[4]).controlled_by(q[0]))
circuit.append(cirq.SQRT_ISWAP(q[1], q[4]).controlled_by(q[2]))
circuit.append(cirq.T(q[1]))

cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=5).on(q[0],q[3],q[4],q[1],q[2]) 
sub_circuit = cirq.Circuit() 
sub_op = cirq.CircuitOperation(sub_circuit.freeze()) 
circuit.append(cirq.measure(q[5], key="c")) 
circuit.append(cirq.measure([q[3],q[0]], key="ca")) 
dc_cond = cirq.BitMaskKeyCondition.create_equal_mask('ca', bitmask=1)
circuit.append(sub_op.with_classical_controls("c", "dc_cond")) 

cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=3).on(q[1],q[2],q[3]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=5, permutation={2: 4, 1: 1, 0: 3, 3: 2, 4: 0}).on(q[4],q[3],q[0],q[1],q[2]) 
circuit.append(cirq.rz(0.02454369260617026).on(q[3]).controlled_by(q[2]))
circuit.append(cirq.rz(0.7853981633974483).on(q[0]).controlled_by(q[2]))
circuit.append(cirq.CCX(q[3], q[1], q[0]))
circuit.append(cirq.SQRT_ISWAP(q[4], q[1]))
circuit.append(cirq.CZ(q[1], q[2]))
circuit.append(cirq.X(q[2]).controlled_by(q[1]))
circuit.append(cirq.S(q[0]).controlled_by(q[1]))
circuit.append(cirq.CCX(q[1], q[2], q[0]).controlled_by(q[3]))
circuit.append(cirq.X(q[4]))
circuit.append(cirq.PhasedISwapPowGate(phase_exponent=0.39269908169872414,exponent=1.5707963267948966).on(q[1], q[0]))

cirq.contrib.acquaintance.AcquaintanceOperation([q[1],q[3],q[2]], [1, 3, 2]) 
