import cirq
from cirq.transformers import *

q = cirq.LineQubit.range(6) 
circuit = cirq.Circuit()


cirq.contrib.acquaintance.AcquaintanceOperation([q[3],q[0]], [3, 0]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=5).on(q[2],q[1],q[3],q[4],q[0]) 
circuit.append(cirq.MSGate(rads=0.7853981633974483).on(q[4], q[2]))
circuit.append(cirq.SWAP(q[0], q[1]).controlled_by(q[3]))
circuit.append(cirq.SWAP(q[1], q[0]))
circuit.append(cirq.SQRT_ISWAP_INV(q[3], q[0]))
circuit.append(cirq.ry(0.006135923151542565).on(q[3]).controlled_by(q[0]))
circuit.append(cirq.CCZ(q[4], q[3], q[2]))
circuit.append(cirq.PhasedISwapPowGate(phase_exponent=0.02454369260617026,exponent=0.7853981633974483).on(q[3], q[0]).controlled_by(q[2]))
circuit.append(cirq.XPowGate(exponent=0.0030679615757712823).on(q[0]))
circuit.append(cirq.XXPowGate(exponent=0.04908738521234052).on(q[0], q[2]).controlled_by(q[4]))
circuit.append(cirq.CNOT(q[4], q[1]).controlled_by(q[3]))

cirq.contrib.acquaintance.AcquaintanceOperation([q[0],q[2]], [0, 2]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=5, permutation={1: 0, 4: 1, 2: 4, 0: 2, 3: 3}).on(q[4],q[3],q[2],q[0],q[1]) 
sub_circuit = cirq.Circuit() 
sub_op = cirq.CircuitOperation(sub_circuit.freeze()) 
circuit.append(cirq.measure(q[5], key="c")) 
circuit.append(cirq.measure([q[4],q[2]], key="ca")) 
dc_cond = cirq.BitMaskKeyCondition.create_equal_mask('ca', bitmask=1)
circuit.append(sub_op.with_classical_controls("c", dc_cond)) 

cirq.contrib.acquaintance.AcquaintanceOpportunityGate(num_qubits=4).on(q[0],q[3],q[4],q[2]) 
cirq.contrib.acquaintance.CircularShiftGate(shift=1, num_qubits=2).on(q[3],q[0]) 
circuit.append(cirq.SQRT_ISWAP_INV(q[0], q[3]).controlled_by(q[2]))
circuit.append(cirq.SWAP(q[0], q[3]).controlled_by(q[4]))
circuit.append(cirq.YYPowGate(exponent=0.02454369260617026).on(q[2], q[4]).controlled_by(q[1]))
circuit.append(cirq.T(q[0]).controlled_by(q[4]))
circuit.append(cirq.rz(0.39269908169872414).on(q[1]).controlled_by(q[2]))
circuit.append(cirq.ry(0.0030679615757712823).on(q[3]))
circuit.append(cirq.SWAP(q[1], q[0]))
circuit.append(cirq.Y(q[0]).controlled_by(q[4]))
circuit.append(cirq.S(q[0]).controlled_by(q[4]))
circuit.append(cirq.Z(q[2]))

cirq.contrib.acquaintance.AcquaintanceOpportunityGate(num_qubits=2).on(q[2],q[4]) 
cirq.contrib.acquaintance.LinearPermutationGate(num_qubits=4, permutation={3: 1, 0: 3, 2: 2, 1: 0}).on(q[1],q[0],q[3],q[2]) 
circuit.append(cirq.measure(q, key="m")) 
circuit = optimize_for_target_gateset(circuit)
circuit = stratified_circuit(circuit)
circuit = expand_composite(circuit)
simulator = cirq.Simulator() 
result = simulator.run(circuit, repetitions=500) 
print(result.histogram(key='m'))